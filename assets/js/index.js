/* ── DEVICE SELECTOR DRAG SCROLL ── */
(function(){
  var el = document.getElementById('conn-scroll');
  if(!el) return;
  var isDown = false, startX, scrollLeft;
  el.parentElement.addEventListener('mousedown', function(e){isDown=true; startX=e.pageX - el.offsetLeft; scrollLeft=el.parentElement.scrollLeft;});
  el.parentElement.addEventListener('mouseleave', function(){isDown=false;});
  el.parentElement.addEventListener('mouseup', function(){isDown=false;});
  el.parentElement.addEventListener('mousemove', function(e){
    if(!isDown) return;
    e.preventDefault();
    var x = e.pageX - el.offsetLeft;
    var walk = (x - startX) * 1.5;
    el.parentElement.scrollLeft = scrollLeft - walk;
  });
  // Touch support
  var tStartX, tScrollLeft;
  el.parentElement.addEventListener('touchstart', function(e){tStartX=e.touches[0].pageX; tScrollLeft=el.parentElement.scrollLeft;},{passive:true});
  el.parentElement.addEventListener('touchmove', function(e){
    var x = e.touches[0].pageX;
    el.parentElement.scrollLeft = tScrollLeft - (x - tStartX);
  },{passive:true});
})();

